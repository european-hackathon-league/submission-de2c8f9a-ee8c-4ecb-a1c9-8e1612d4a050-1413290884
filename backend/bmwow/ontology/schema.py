"""Generate portable JSON contracts from the Python source of truth."""

import argparse
import json
from dataclasses import asdict
from pathlib import Path
from typing import get_args

from .models import ONTOLOGY_VERSION, Domain, GraphBundle, Node, RelationshipType
from .relationships import RELATIONSHIPS


def build_schema() -> dict:
    schema = GraphBundle.model_json_schema(mode="validation")
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = f"urn:bmwow:ontology:{ONTOLOGY_VERSION}"
    schema["title"] = f"BMW product decision ontology v{ONTOLOGY_VERSION}"
    schema["description"] = (
        "Portable property-graph contract generated from Pydantic models. "
        "Also run bmwow-validate for graph-wide evidence, reference, and review rules."
    )
    schema["x-generated-by"] = "uv run bmwow-schema; do not edit this file by hand"
    return schema


def build_vocabulary() -> dict:
    if set(RELATIONSHIPS) != set(get_args(RelationshipType)):
        raise RuntimeError("Model and relationship rule names disagree")
    node_models = get_args(get_args(Node)[0])
    node_types = {
        get_args(model.model_fields["type"].annotation)[0]: {"description": model.__doc__}
        for model in node_models
    }
    known_nodes = set(node_types)
    for rule in RELATIONSHIPS.values():
        if not set(rule.source_types + rule.target_types) <= known_nodes:
            raise RuntimeError("Relationship rule references an unknown node type")
    return {
        "ontology_version": ONTOLOGY_VERSION,
        "node_types": node_types,
        "relationships": {name: asdict(rule) for name, rule in RELATIONSHIPS.items()},
        "domains": list(get_args(Domain)),
        "scope_authority": (
            "properties.context is authoritative; do not separately maintain conflicting ABOUT edges."
        ),
        "review_state": (
            "Derived from human Decision events for the exact Requirement id and revision. "
            "A new revision starts unreviewed."
        ),
        "storage": (
            "SQL tables, join tables, or a NetworkX MultiDiGraph can represent the same contract. "
            "No storage engine is required by this ontology."
        ),
    }


def render_contracts() -> dict[str, str]:
    return {
        name: json.dumps(value, ensure_ascii=False, indent=2) + "\n"
        for name, value in {
            "schema.json": build_schema(),
            "vocabulary.json": build_vocabulary(),
        }.items()
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("contracts/ontology"),
        help="Contract directory, relative to the current directory (default: contracts/ontology)",
    )
    parser.add_argument("--check", action="store_true", help="Fail if generated files are stale")
    args = parser.parse_args()
    failed = False
    try:
        contracts = render_contracts()
        if not args.check:
            args.output_dir.mkdir(parents=True, exist_ok=True)
        for name, expected in contracts.items():
            path = args.output_dir / name
            if args.check:
                if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                    print(f"STALE {path}; run uv run bmwow-schema")
                    failed = True
                else:
                    print(f"CURRENT {path}")
            else:
                path.write_text(expected, encoding="utf-8")
                print(f"GENERATED {path}")
    except (OSError, RuntimeError) as error:
        parser.exit(1, f"{error}\n")
    raise SystemExit(1 if failed else 0)


if __name__ == "__main__":
    main()
